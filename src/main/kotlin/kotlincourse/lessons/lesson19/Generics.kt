//Создайте функцию swap с дженериком, которая будет принимать изменяемый список и два индекса и возвращать неизменяемый список того же типа,
// но в котором два элемента по индексам поменяны между собой местами.
fun <T> swap(
    list: MutableList<T>,
    index1: Int,
    index2: Int
): List<T> {
    val switch1 = list[index1]
    val switch2 = list[index2]
    list.add(index1, switch2)
    list.add(index2, switch1)
    return list.toList()

}

//Напишите функцию mergeLists с дженериком ограниченным типом Number, которая принимает два списка типа T
// и возвращает список Double с суммой элементов списка. Если списки разных размеров то отсутствующие элементы принимать за ноль.
fun <T : Number> mergeList(
    list1: List<T>,
    list2: List<T>
): List<Double> {
    val size = max(list1.size, list2.size)
    val sum = mutableListOf<Double>()
    for (i in 0..<size) {
        val arg1 = list1.getOrNull(i)?.toDouble() ?: 0.0
        val arg2 = list2.getOrNull(i,)?.toDouble() ?: 0.0
        sum.add(arg1 + arg2)
    }
    return sum.toList()
}

